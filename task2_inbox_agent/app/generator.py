def save_synthetic_emails(filepath: str) -> int:
    """Generate and persist 55 synthetic emails to JSON."""
    emails = generate_synthetic_emails()
    path = Path(filepath)
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        json.dump([e.model_dump() for e in emails], f, indent=2)
    return len(emails)
